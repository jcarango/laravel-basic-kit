        <h1 class="text-3xl font-bold text-slate-900 mb-6">POLÍTICA DE TRATAMIENTO DE DATOS PERSONALES</h1>
        <p class="text-sm text-gray-500 mb-8">De acuerdo con lo establecido en la Ley Estatutaria 1581 de 2012 y el Decreto Reglamentario 1377 de 2013 de la República de Colombia.</p>

        <div class="space-y-6 prose max-w-none text-slate-600">
            <h2 class="text-xl font-bold text-slate-900">1. Objetivo</h2>
            <p>El presente documento tiene como objetivo establecer los criterios para la recolección, almacenamiento, uso, circulación y supresión de los datos personales tratados por <strong>DEMOSOL</strong>, garantizando el derecho constitucional que tienen todas las personas a conocer, actualizar y rectificar la información que se haya recogido sobre ellas en nuestras bases de datos.</p>

            <h2 class="text-xl font-bold text-slate-900">2. Alcance</h2>
            <p>Esta política aplica para toda la información personal registrada en las bases de datos de DEMOSOL, quien actúa en calidad de Responsable del tratamiento de los datos personales.</p>

            <h2 class="text-xl font-bold text-slate-900">3. Finalidad del Tratamiento de Datos</h2>
            <p>Los datos personales proporcionados serán utilizados exclusivamente para los siguientes propósitos:</p>
            <ul class="list-disc pl-5 space-y-2">
                <li>Registro y gestión de información en la plataforma para control electoral, formación de líderes y afiliaciones.</li>
                <li>Evaluación de perfiles profesionales y currículos (Hojas de Vida) para la conformación de equipos, campañas o integración laboral/voluntaria dentro del ecosistema DEMOSOL.</li>
                <li>Envío de comunicaciones, notificaciones de eventos, boletines informativos y mensajes vía correo electrónico, SMS o WhatsApp.</li>
                <li>Análisis estadístico y demográfico interno para mejorar las estrategias y propuestas en el territorio.</li>
                <li>Dar cumplimiento a obligaciones legales o contractuales contraídas con los titulares.</li>
            </ul>

            <h2 class="text-xl font-bold text-slate-900">4. Derechos de los Titulares</h2>
            <p>Como titular de sus datos personales, usted tiene derecho a:</p>
            <ul class="list-disc pl-5 space-y-2">
                <li><strong>Conocer, actualizar y rectificar</strong> sus datos personales frente a DEMOSOL. Este derecho se podrá ejercer, entre otros frente a datos parciales, inexactos, incompletos, fraccionados, que induzcan a error, o aquellos cuyo tratamiento esté expresamente prohibido o no haya sido autorizado.</li>
                <li><strong>Solicitar prueba de la autorización</strong> otorgada para el tratamiento de sus datos.</li>
                <li><strong>Ser informado</strong>, previa solicitud, respecto del uso que se le ha dado a sus datos personales.</li>
                <li><strong>Revocar la autorización</strong> y/o solicitar la supresión del dato cuando en el tratamiento no se respeten los principios, derechos y garantías constitucionales y legales.</li>
                <li><strong>Acceder en forma gratuita</strong> a sus datos personales que hayan sido objeto de tratamiento.</li>
            </ul>

            <h2 class="text-xl font-bold text-slate-900">5. Atención de Peticiones, Consultas y Reclamos</h2>
            <p>El área encargada de la atención de las peticiones, consultas y reclamos será el equipo de soporte de DEMOSOL. Los titulares pueden ejercer sus derechos enviando una comunicación al correo electrónico institucional oficial de la organización o mediante el formato de contacto disponible en el sitio web.</p>

            <h2 class="text-xl font-bold text-slate-900">6. Seguridad de la Información</h2>
            <p>DEMOSOL se compromete a adoptar las medidas técnicas, humanas y administrativas necesarias para garantizar la seguridad de los datos personales, evitando su adulteración, pérdida, consulta, uso o acceso no autorizado o fraudulento.</p>

            <h2 class="text-xl font-bold text-slate-900">7. Vigencia de la Política</h2>
            <p>La presente Política rige a partir de la fecha de su publicación en nuestro portal web. Las bases de datos en las que se registrarán los datos personales tendrán una vigencia igual al tiempo en que se mantenga y utilice la información para las finalidades descritas, o por el período establecido en normas legales aplicables.</p>

            <div class="mt-8 p-4 bg-amber-50 border border-amber-200 rounded">
